"""
Исключения библиотеки: одна иерархия, чтобы можно было поймать любую ошибку отчета одним ``except ReportError``.

Что и когда бросается:

* ошибка в содержимом отчета или окружении - наследники ``ReportError`` (ниже);
* неправильный вызов функции (лишнее имя поля в ``evolve``, пустой список файлов, не тот тип данных
  в ``table_from``) - обычные ``TypeError`` и ``ValueError``: это ошибка программиста, а не отчета.

::

    ReportError
    |-- ResolveError          метки, ссылки и номера: что-то не сходится в самом отчете
    |-- MarkdownError         документ Markdown нельзя превратить в отчет
    |-- BibliographyError     список источников нельзя составить: нет записи, файла или стиля CSL
    |-- MathConversionError   формулу нельзя превратить в OMML
    `-- PandocError           pandoc не найден, не запустился или завершился с ошибкой

Предупреждение ``MarkupInPlainTextWarning`` (через ``warnings``) - не ошибка отчета: документ собирается, но
выглядит не так, как, скорее всего, задумано.
"""

from __future__ import annotations


class ReportError(Exception):
    """
    Базовый класс всех ошибок, которые библиотека бросает намеренно.
    """


class ResolveError(ReportError):
    """
    Отчет противоречит сам себе: повторяющаяся метка, ссылка на неизвестную метку или на блок без номера,
    слишком много приложений.
    """


class MarkdownError(ReportError):
    """
    Документ Markdown нельзя превратить в отчет: неподдерживаемая конструкция или нарушенная договоренность
    (см. ``studen_doc.frontends.markdown``).
    """


class BibliographyError(ReportError):
    """
    Список источников не составить: ссылка на неизвестную запись, нет файла библиографии или стиля CSL,
    библиографию не удалось оформить.
    """


class MathConversionError(ReportError):
    """
    Формулу не удалось превратить в OMML (или конвертер недоступен).
    """


class PandocError(ReportError):
    """
    pandoc не найден, не запустился, не уложился во время или завершился с ошибкой.
    """


class MarkupInPlainTextWarning(UserWarning):
    """
    В обычной строке есть законченная формула (``$x^2$`` или ``$$x^2$$``): строка выводится буквально, и формула
    останется знаками доллара. Разметка включается через ``Md("...")``; если доллары нужны как есть, предупреждение
    отключается: ``warnings.filterwarnings("ignore", category=MarkupInPlainTextWarning)``.
    """
