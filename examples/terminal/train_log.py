"""
Учебная программа: цветной журнал обучения. Нужна демонстрации, как вывод терминала попадает в отчет.
"""

ESC = chr(27)


def paint(text: str, *codes: int) -> str:
    """
    Текст в escape-последовательностях SGR: ``paint("ok", 1, 32)`` - жирный зеленый.
    """
    return f"{ESC}[{';'.join(map(str, codes))}m{text}{ESC}[0m"


EPOCHS = [(1, 0.912, 0.61), (2, 0.644, 0.74), (3, 0.431, 0.83), (4, 0.298, 0.88), (5, 0.217, 0.912)]

print(paint("Обучение модели классификации", 1, 4))
print(paint("[инфо]", 36), "загружено 1200 записей, признаков: 14")
print(paint("[предупр.]", 33), "в столбце age 14 пропусков, заполнены медианой")
print(paint("  подробности: порог заполнения 0.05, метод median", 2))
print()
for epoch, loss, accuracy in EPOCHS:
    color = 31 if loss > 0.5 else 33 if loss > 0.3 else 32
    print(f"эпоха {epoch}/5  потери {paint(f'{loss:.3f}', color)}  точность {accuracy:.1%}")
print()
print("┌──────────────┬────────┬────────┐")
print("│ метрика      │  обуч. │  тест  │")
print("├──────────────┼────────┼────────┤")
print(f"│ точность     │ {paint('0.940', 32)}  │ {paint('0.912', 1, 32)}  │")
print(f"│ полнота      │ {paint('0.902', 32)}  │ {paint('0.871', 33)}  │")
print(f"│ F1-мера      │ {paint('0.920', 32)}  │ {paint('0.889', 33)}  │")
print("└──────────────┴────────┴────────┘")
print()
